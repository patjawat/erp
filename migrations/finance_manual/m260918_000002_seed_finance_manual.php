        $catSort = 0;
        foreach ($this->data() as $cat) {
            $catSort += 10;
            $this->insert('{{%finance_manual_category}}', [
                'code' => $cat['code'],
                'title' => $cat['title'],
                'icon' => $cat['icon'],
                'description' => $cat['description'],
                'sort_order' => $catSort,
                'is_active' => 1,
                'created_at' => $now,
                'updated_at' => $now,
            ]);
            $categoryId = (int) $this->db->getLastInsertID();

            $topicSort = 0;
            foreach ($cat['topics'] as $topic) {
                $topicSort += 10;
                $this->insert('{{%finance_manual_topic}}', [
                    'category_id' => $categoryId,
                    'title' => $topic['title'],
                    'intro' => $topic['intro'] ?? null,
                    'note' => $topic['note'] ?? null,
                    'sort_order' => $topicSort,
                    'is_active' => 1,
                    'created_at' => $now,
                    'updated_at' => $now,
                ]);
                $topicId = (int) $this->db->getLastInsertID();

                $itemSort = 0;
                foreach ($topic['items'] as $item) {
                    $itemSort += 10;
                    [$content, $kind] = is_array($item) ? [$item[0], $item[1]] : [$item, 'doc'];
                    $this->insert('{{%finance_manual_item}}', [
